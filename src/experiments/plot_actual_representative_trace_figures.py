_SCENARIO_CACHE: dict[tuple[int, str, int], dict[str, Any]] = {}


def parse_scenario_index(scenario_name: str) -> int:
    # Example: large_00248_overloaded_clustered_poisson_tight
    parts = scenario_name.split("_")
    if len(parts) < 2 or parts[0] != "large":
        raise ValueError(f"Could not parse large-scale scenario id from: {scenario_name}")
    return int(parts[1])


def load_selected_examples(input_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    selected_path = input_dir / "selected_representative_states_full_rows.csv"
    perf_path = input_dir / "selected_representative_state_performance_long.csv"

    if not selected_path.exists():
        raise FileNotFoundError(
            f"Missing selected states file: {selected_path}\n"
            "Run select_representative_heuristic_states.py first."
        )

    if not perf_path.exists():
        raise FileNotFoundError(
            f"Missing performance file: {perf_path}\n"
            "Run select_representative_heuristic_states.py first."
        )

    return pd.read_csv(selected_path), pd.read_csv(perf_path)


def get_scenario_params(
    scenario_name: str,
    seed: int,
    scenario_mix: str = "baseline",
    n_scenarios: int | None = None,
    min_threat_speed: float = 0.05,
    min_boundary_speed: float = 0.05,
):
    scenario_index = parse_scenario_index(scenario_name)

    # To reconstruct a scenario exactly, the plotting script must use the same
    # large-scale generator seed and scenario mix used in the rollout experiment.
    # For long runs, passing --n-scenarios avoids repeated partial regeneration.
    required_n = scenario_index + 1
    effective_n = max(required_n, int(n_scenarios)) if n_scenarios is not None else required_n

    cache_key = (
        int(seed),
        str(scenario_mix),
        int(effective_n),
        float(min_threat_speed),
        float(min_boundary_speed),
    )
    if cache_key not in _SCENARIO_CACHE:
        _SCENARIO_CACHE[cache_key] = make_large_scale_scenarios(
            n_scenarios=effective_n,
            seed=seed,
            scenario_mix=scenario_mix,
            min_threat_speed=min_threat_speed,
            min_boundary_speed=min_boundary_speed,
        )

    scenarios = _SCENARIO_CACHE[cache_key]

    if scenario_name not in scenarios:
        raise KeyError(
            f"Scenario {scenario_name} was not regenerated. "
            f"Check that generator seed={seed}, scenario_mix={scenario_mix!r}, "
            f"and n_scenarios={effective_n} match the original rollout."
        )

    return scenarios[scenario_name].params


def parse_bool_value(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return False
    if isinstance(value, (int, np.integer)):
        return bool(value)
    if isinstance(value, str):
        return value.strip().lower() in {"1", "true", "yes", "y"}
    return bool(value)


def replay_behavior_to_selected_state(
    row: pd.Series,
    generator_seed: int,
    scenario_mix: str = "baseline",
    n_scenarios: int | None = None,
    min_threat_speed: float = 0.05,
    min_boundary_speed: float = 0.05,
) -> SimEnv:
    """
    Reconstruct the exact environment snapshot used by the state-labeling dataset.

    The selected row was generated by:
    1. Running a behavior heuristic.
    2. Labeling every decision state.
    3. Assigning state_id in that behavior trajectory.

    This function repeats that process until the requested state_id.
    """

    scenario_name = str(row["scenario"])
    params = get_scenario_params(
        scenario_name,
        seed=generator_seed,
        scenario_mix=scenario_mix,
        n_scenarios=n_scenarios,
        min_threat_speed=min_threat_speed,
        min_boundary_speed=min_boundary_speed,
    )

    behavior_heuristic = str(row.get("behavior_heuristic", "NI"))
    behavior_preempt = parse_bool_value(row.get("behavior_preempt", False))
    target_state_id = int(row.get("state_id", 0))

    env = SimEnv(params)
    heuristic_map = make_heuristics(seed=params.seed)

    if behavior_heuristic not in heuristic_map:
        raise KeyError(f"Unknown behavior heuristic: {behavior_heuristic}")

    behavior_h = heuristic_map[behavior_heuristic]

    target_id = None
    state_counter = 0

    while not env.done():
        active = env.active_threats()
        should_label = len(active) > 0

        if should_label:
            if state_counter == target_state_id:
                return copy.deepcopy(env)
            state_counter += 1

        active = env.active_threats()

        if target_id is None or all(th.id != target_id for th in active):
            target_id = behavior_h(active, env.interceptor_pos, params.v_interceptor)

        events = env.step(target_id)

        if behavior_preempt and events.get("arrival", 0) > 0:
            active_after = env.active_threats()
            target_id = behavior_h(active_after, env.interceptor_pos, params.v_interceptor)

    raise RuntimeError(
        f"Could not replay to state_id={target_state_id} for scenario={scenario_name}. "
        f"Reached only {state_counter} labeled states."
    )


def snapshot_features(env: SimEnv) -> dict[str, Any]:
    active = env.active_threats()

    if not active:
        return {
            "N_active": 0,
            "min_ttb": np.inf,
            "mean_ttb": np.inf,
            "min_tti": np.inf,
            "mean_tti": np.inf,
            "min_slack": np.inf,
            "mean_slack": np.inf,
            "min_positive_slack": np.inf,
            "count_feasible": 0,
            "count_negative_slack": 0,
            "feasible_ratio": 0.0,
        }

    ttbs = np.array([time_to_boundary_x0(th.pos, th.vel) for th in active], dtype=float)
    ttis = np.array([time_to_intercept(env.interceptor_pos, th.pos, env.p.v_interceptor, th.vel) for th in active], dtype=float)
    slacks = np.array([slack(env.interceptor_pos, th, env.p.v_interceptor) for th in active], dtype=float)
    positive = slacks[slacks >= 0]

    finite_ttbs = ttbs[np.isfinite(ttbs)]
    finite_ttis = ttis[np.isfinite(ttis)]
    finite_slacks = slacks[np.isfinite(slacks)]

    return {
        "N_active": int(len(active)),
        "min_ttb": float(np.min(finite_ttbs)) if len(finite_ttbs) else np.inf,
        "mean_ttb": float(np.mean(finite_ttbs)) if len(finite_ttbs) else np.inf,
        "min_tti": float(np.min(finite_ttis)) if len(finite_ttis) else np.inf,
        "mean_tti": float(np.mean(finite_ttis)) if len(finite_ttis) else np.inf,
        "min_slack": float(np.min(finite_slacks)) if len(finite_slacks) else np.inf,
        "mean_slack": float(np.mean(finite_slacks)) if len(finite_slacks) else np.inf,
        "min_positive_slack": float(np.min(positive)) if len(positive) else np.inf,
        "count_feasible": int(np.sum(slacks >= 0)),
        "count_negative_slack": int(np.sum(slacks < 0)),
        "feasible_ratio": float(np.mean(slacks >= 0)),
    }


def trace_from_env_snapshot(
    env_snapshot: SimEnv,
    heuristic_name: str,
    preempt: bool = False,
) -> dict[str, Any]:
    """
    Continue an actual simulation from the selected environment state
    using a fixed heuristic, while recording a trace.
    """

    env = copy.deepcopy(env_snapshot)
    heuristic_map = make_heuristics(seed=env.p.seed)

    if heuristic_name not in heuristic_map:
        raise KeyError(f"Unknown heuristic: {heuristic_name}")

    h = heuristic_map[heuristic_name]

    start_t = float(env.t)
    start_intercepted = int(env.intercepted)
    start_escaped = int(env.escaped)
    start_spawned = int(env.spawned)

    target_id = None
    trace: list[dict[str, Any]] = []

    while not env.done():
        active_before = env.active_threats()

        if target_id is None or all(th.id != target_id for th in active_before):
            target_id = h(active_before, env.interceptor_pos, env.p.v_interceptor)

        trace.append(
            {
                "t": float(env.t),
                "relative_t": float(env.t - start_t),
                "interceptor_pos": env.interceptor_pos.copy(),
                "chosen_target_id": target_id,
                "active_threats": [
                    {
                        "id": th.id,
                        "pos": th.pos.copy(),
                        "vel": th.vel.copy(),
                        "ttb": float(time_to_boundary_x0(th.pos, th.vel)),
                        "tti": float(time_to_intercept(env.interceptor_pos, th.pos, env.p.v_interceptor, th.vel)),
                        "slack": float(slack(env.interceptor_pos, th, env.p.v_interceptor)),
                        "intercept_point": predicted_intercept_point(
                            env.interceptor_pos,
                            th.pos,
                            th.vel,
                            env.p.v_interceptor,
                        ).copy(),
                    }
                    for th in active_before
                ],
                "features": snapshot_features(env),
                "intercepted_so_far": int(env.intercepted - start_intercepted),
                "escaped_so_far": int(env.escaped - start_escaped),
                "spawned_so_far": int(env.spawned - start_spawned),
                "total_intercepted": int(env.intercepted),
                "total_escaped": int(env.escaped),
                "total_spawned": int(env.spawned),
                "v_interceptor": float(env.p.v_interceptor),
            }
        )

        events = env.step(target_id)

        if preempt and events.get("arrival", 0) > 0:
            active_after = env.active_threats()
            target_id = h(active_after, env.interceptor_pos, env.p.v_interceptor)

    summary = {
        "heuristic": heuristic_name,
        "start_t": start_t,
        "future_intercepted": int(env.intercepted - start_intercepted),
        "future_escaped": int(env.escaped - start_escaped),
        "future_spawned": int(env.spawned - start_spawned),
        "final_intercepted": int(env.intercepted),
        "final_escaped": int(env.escaped),
        "final_spawned": int(env.spawned),
    }

    return {"trace": trace, "summary": summary}


def choose_runner_up(perf_df: pd.DataFrame, selected_for: str) -> str:
    g = perf_df[perf_df["selected_for"] == selected_for].copy()

    if g.empty:
        raise ValueError(f"No performance rows for selected_for={selected_for}")

    g = g.sort_values(
        ["future_intercepted", "future_escaped", "rank"],
        ascending=[False, True, True],
    )

    for _, row in g.iterrows():
        h = str(row["heuristic"])
        if h != selected_for:
            return h

    raise ValueError(f"Could not determine runner-up for {selected_for}")


def pick_frame_times(trace_a: list[dict[str, Any]], trace_b: list[dict[str, Any]], max_frames: int) -> list[float]:
    if not trace_a:
        raise ValueError("Winner trace is empty.")
    if not trace_b:
        raise ValueError("Runner-up trace is empty.")

    # Limit to the time range shared by both traces.
    end_t = min(trace_a[-1]["t"], trace_b[-1]["t"])
    start_t = max(trace_a[0]["t"], trace_b[0]["t"])

    if end_t <= start_t:
        return [start_t]

    n = max(2, max_frames)
    return np.linspace(start_t, end_t, n).tolist()


def nearest_state_at_time(trace: list[dict[str, Any]], t: float) -> dict[str, Any]:
    idx = int(np.argmin([abs(state["t"] - t) for state in trace]))
    return trace[idx]


def _state_focus_points(state: dict[str, Any]) -> list[np.ndarray]:
    """Points that define the local region of interest for one plotted frame."""
    pts: list[np.ndarray] = []
    pI = np.array(state["interceptor_pos"], dtype=float)
    pts.append(pI)

    chosen_id = state.get("chosen_target_id")
    for th in state.get("active_threats", []):
        if th.get("id") == chosen_id:
            pos = np.array(th["pos"], dtype=float)
            pts.append(pos)
            ip = np.array(th.get("intercept_point", pos), dtype=float)
            if np.all(np.isfinite(ip)):
                pts.append(ip)
            break
    return pts


def collect_plot_limits(
    traces: list[list[dict[str, Any]]],
    frame_times: list[float] | None = None,
    context_radius: float = 12.0,
    max_left_penetration: float = 3.0,
) -> tuple[tuple[float, float], tuple[float, float]]:
    """
    Compute a local zoom window for equal-aspect plots.

    Earlier versions used the entire rollout trace and all future intercept
    points. With ax.set_aspect('equal'), this often wasted most of the figure
    on x<0 or on far-away targets. This version focuses on the frames that are
    actually plotted, the interceptor, the chosen target, the chosen lead point,
    and nearby active targets.
    """
    xs: list[float] = [0.0]
    ys: list[float] = [0.0]

    if frame_times is None:
        frame_times = []

    for trace in traces:
        if not trace:
            continue

        if frame_times:
            states = [nearest_state_at_time(trace, t) for t in frame_times]
        else:
            states = trace

        # Include path only up to the last displayed state, not the whole future.
        max_t = max(float(st["t"]) for st in states)
        for st in trace:
            if float(st["t"]) <= max_t:
                p = np.array(st["interceptor_pos"], dtype=float)
                xs.append(float(p[0]))
                ys.append(float(p[1]))

        for state in states:
            focus_pts = _state_focus_points(state)
            for fp in focus_pts:
                if np.all(np.isfinite(fp)):
                    xs.append(float(fp[0]))
                    ys.append(float(fp[1]))

            for th in state.get("active_threats", []):
                pos = np.array(th["pos"], dtype=float)
                if not np.all(np.isfinite(pos)):
                    continue

                # Keep nearby context targets, but do not let far-away targets
                # determine the zoom window.
                if focus_pts:
                    nearest_focus_dist = min(float(np.linalg.norm(pos - fp)) for fp in focus_pts)
                else:
                    nearest_focus_dist = 0.0

                if nearest_focus_dist <= context_radius:
                    xs.append(float(pos[0]))
                    ys.append(float(pos[1]))

                    # Include only this target's lead point if it is part of the
                    # local context; otherwise remote lead points can distort zoom.
                    ip = np.array(th.get("intercept_point", pos), dtype=float)
                    if np.all(np.isfinite(ip)):
                        xs.append(float(ip[0]))
                        ys.append(float(ip[1]))

    if len(xs) <= 1:
        return (-1, 10), (-10, 10)

    xmin_data, xmax_data = min(xs), max(xs)
    ymin_data, ymax_data = min(ys), max(ys)

    x_range = max(1.0, xmax_data - xmin_data)
    y_range = max(1.0, ymax_data - ymin_data)
    xpad = max(0.75, 0.10 * x_range)
    ypad = max(0.75, 0.10 * y_range)

    # Show the boundary and only a bounded part of x<0 unless the plotted local
    # path actually requires a little more. This prevents the left side from
    # dominating the visualization.
    xmin = xmin_data - xpad
    xmin = max(xmin, -abs(max_left_penetration))
    xmin = min(xmin, -0.75)
    xmax = xmax_data + xpad
    ymin = ymin_data - ypad
    ymax = ymax_data + ypad

    width = xmax - xmin
    height = ymax - ymin

    # Preserve equal aspect without expanding symmetrically into x<0.
    # If the y-range is larger, add the extra width mostly to the right.
    if height > width:
        xmax += height - width
    elif width > height:
        extra = (width - height) / 2.0
        ymin -= extra
        ymax += extra

    return (xmin, xmax), (ymin, ymax)

def fmt(x: Any, digits: int = 2) -> str:
    try:
        x = float(x)
        if np.isinf(x):
            return "inf"
        if np.isnan(x):
            return "NA"
        if abs(x - round(x)) < 1e-9:
            return str(int(round(x)))
        return f"{x:.{digits}f}"
    except Exception:
        return str(x)


def frontier_cluster_member_ids(state: dict[str, Any]) -> set[int]:
    """
    Reconstruct the Frontier-Cluster neighborhood used in this plotted state.
    This is used only for visualization, to highlight the dense local cluster.
    """
    active = state.get("active_threats", [])
    if not active:
        return set()

    pI = np.array(state["interceptor_pos"], dtype=float)
    vI = float(state.get("v_interceptor", 1.0))
    r = max(vI * DEFAULT_CLUSTER_TIME_WINDOW, 1e-9)

    def cluster_around(seed: dict[str, Any]) -> list[dict[str, Any]]:
        seed_pos = np.array(seed["pos"], dtype=float)
        return [
            other
            for other in active
            if np.linalg.norm(np.array(other["pos"], dtype=float) - seed_pos) <= r
        ]

    clusters = [(seed, cluster_around(seed)) for seed in active]
    _, chosen_cluster = max(
        clusters,
        key=lambda item: (
            len(item[1]),
            -min(float(member["pos"][0]) for member in item[1]),
            -np.linalg.norm(np.array(item[0]["pos"], dtype=float) - pI),
        ),
    )
    return {int(member["id"]) for member in chosen_cluster}


def frontier_cluster_size(state: dict[str, Any]) -> int:
    return len(frontier_cluster_member_ids(state))


def plot_frame(
    ax,
    state: dict[str, Any],
    trace: list[dict[str, Any]],
    policy_name: str,
    frame_time: float,
    xlim: tuple[float, float],
    ylim: tuple[float, float],
    is_winner: bool,
    show_ylabel: bool,
) -> None:
    # Penetration region
    ax.axvspan(xlim[0], 0, color="#ffdddd", alpha=0.45, zorder=0)
    ax.axvline(0, color="red", linestyle="--", linewidth=1.4, zorder=1)

    # Interceptor path until this time
    path_points = [
        np.array(s["interceptor_pos"], dtype=float)
        for s in trace
        if s["t"] <= state["t"]
    ]
    if len(path_points) >= 2:
        path = np.vstack(path_points)
        ax.plot(path[:, 0], path[:, 1], color="black", linewidth=1.7, alpha=0.85, zorder=2)

    pI = np.array(state["interceptor_pos"], dtype=float)

    # Threats and velocity arrows
    active = state["active_threats"]
    chosen_id = state["chosen_target_id"]
    cluster_member_ids = frontier_cluster_member_ids(state) if policy_name == "FCluster" else set()

    for th in active:
        pos = np.array(th["pos"], dtype=float)
        vel = np.array(th["vel"], dtype=float)
        is_chosen = th["id"] == chosen_id

        color = "#1f77b4"
        size = 38
        z = 3

        edgecolor = "black"
        linewidth = 0.4

        if int(th["id"]) in cluster_member_ids:
            edgecolor = "#ff7f0e"
            linewidth = 1.5
            size = 55

        if is_chosen:
            color = "#2ca02c"
            edgecolor = "black"
            linewidth = 0.8
            size = 75
            z = 5

        ax.scatter(pos[0], pos[1], s=size, color=color, edgecolor=edgecolor, linewidth=linewidth, zorder=z)

        # Target id labels help debug whether a heuristic selected the correct target.
        ax.text(
            pos[0],
            pos[1],
            str(th["id"]),
            fontsize=6.5,
            ha="center",
            va="center",
            color="white" if is_chosen else "black",
            zorder=z + 1,
        )

        # Velocity direction arrow, scaled for visibility.
        speed = np.linalg.norm(vel)
        if speed > 1e-9:
            unit = vel / speed
            arrow_len = max(0.35, 0.05 * (xlim[1] - xlim[0]))
            ax.arrow(
                pos[0],
                pos[1],
                unit[0] * arrow_len,
                unit[1] * arrow_len,
                head_width=0.18,
                head_length=0.28,
                length_includes_head=True,
                color="#1f77b4" if not is_chosen else "#2ca02c",
                alpha=0.55,
                zorder=2,
            )

    # Interceptor
    ax.scatter(pI[0], pI[1], s=90, color="black", marker="*", zorder=6)

    # Chosen target arrow
    chosen = None
    for th in active:
        if th["id"] == chosen_id:
            chosen = th
            break

    if chosen is not None:
        cpos = np.array(chosen["pos"], dtype=float)
        lead_point = np.array(chosen.get("intercept_point", cpos), dtype=float)

        # Current selected target position.
        ax.scatter(
            cpos[0],
            cpos[1],
            s=180,
            facecolors="none",
            edgecolors="#2ca02c",
            linewidth=2.2,
            zorder=6,
        )

        # Lead-pursuit guidance: the interceptor heads toward the predicted
        # future intercept point, not necessarily the target's current position.
        ax.annotate(
            "",
            xy=(lead_point[0], lead_point[1]),
            xytext=(pI[0], pI[1]),
            arrowprops=dict(arrowstyle="->", color="#2ca02c", linewidth=1.6),
            zorder=4,
        )

        ax.scatter(
            lead_point[0],
            lead_point[1],
            s=55,
            color="#2ca02c",
            marker="x",
            linewidth=2.0,
            zorder=7,
        )

        ax.plot(
            [cpos[0], lead_point[0]],
            [cpos[1], lead_point[1]],
            linestyle=":",
            color="#2ca02c",
            linewidth=1.2,
            alpha=0.8,
            zorder=3,
        )

    f = state["features"]
    cluster_line = ""
    if policy_name == "FCluster":
        cluster_line = f"\ncluster size = {frontier_cluster_size(state)}"

    info = (
        f"t = {state['t']:.2f}\n"
        f"N active = {f.get('N_active', len(active))}\n"
        f"min TTB = {fmt(f.get('min_ttb'))}\n"
        f"min slack = {fmt(f.get('min_slack'))}\n"
        f"min +slack = {fmt(f.get('min_positive_slack'))}"
        f"{cluster_line}\n"
        f"future I/E so far = {state['intercepted_so_far']} / {state['escaped_so_far']}"
    )

    # Keep the diagnostic info outside the plotting area.
    # This avoids hiding targets after ax.set_aspect("equal").
    info_compact = " | ".join(info.splitlines())
    ax.text(
        0.5,
        -0.20,
        info_compact,
        transform=ax.transAxes,
        va="top",
        ha="center",
        fontsize=7.2,
        bbox=dict(boxstyle="round,pad=0.22", facecolor="white", edgecolor="gray", alpha=0.95),
        clip_on=False,
    )

    title_prefix = "WINNER" if is_winner else "RUNNER-UP"
    ax.set_title(f"{title_prefix}: {policy_name} | frame t={state['t']:.2f}", fontsize=11)

    ax.set_xlim(*xlim)
    ax.set_ylim(*ylim)
    # Equal aspect ratio is important: otherwise Euclidean nearest-target
    # decisions can look visually wrong when x and y ranges differ.
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlabel("x position")
    if show_ylabel:
        ax.set_ylabel("y position")
    ax.grid(alpha=0.25)

    # Separate legend for every panel, outside the plotted area and adjacent to it.
    # This is intentionally not a central legend, because manual inspection is
    # easier when each subplot is self-contained.
    ax.legend(
        handles=make_shared_legend_handles(),
        loc="upper left",
        bbox_to_anchor=(1.02, 1.00),
        fontsize=7.0,
        frameon=True,
        borderaxespad=0.0,
    )


