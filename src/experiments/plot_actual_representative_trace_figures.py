def plot_trace_comparison(
    selected_for: str,
    scenario_name: str,
    winner_trace: list[dict[str, Any]],
    runner_trace: list[dict[str, Any]],
    winner_summary: dict[str, Any],
    runner_summary: dict[str, Any],
    runner_up: str,
    output_dir: Path,
    max_frames: int,
    panels_per_row: int = 2,
    zoom_context_radius: float = 12.0,
    max_left_penetration: float = 3.0,
) -> Path:
    frame_times = pick_frame_times(winner_trace, runner_trace, max_frames=max_frames)
    xlim, ylim = collect_plot_limits(
        [winner_trace, runner_trace],
        frame_times=frame_times,
        context_radius=zoom_context_radius,
        max_left_penetration=max_left_penetration,
    )

    panel_specs: list[dict[str, Any]] = []
    for t in frame_times:
        panel_specs.append(
            {
                "state": nearest_state_at_time(winner_trace, t),
                "trace": winner_trace,
                "policy_name": selected_for,
                "frame_time": t,
                "is_winner": True,
            }
        )
        panel_specs.append(
            {
                "state": nearest_state_at_time(runner_trace, t),
                "trace": runner_trace,
                "policy_name": runner_up,
                "frame_time": t,
                "is_winner": False,
            }
        )

    n_panels = len(panel_specs)
    n_cols = max(1, min(int(panels_per_row), n_panels))
    n_rows = int(math.ceil(n_panels / n_cols))

    # Two panels per row is usually the clearest layout for manual inspection.
    # Extra horizontal room is reserved for a per-panel legend outside each axis.
    fig_width = max(15.5, 7.9 * n_cols)
    fig_height = max(5.2, 5.15 * n_rows)
    fig, axes = plt.subplots(
        n_rows,
        n_cols,
        figsize=(fig_width, fig_height),
        squeeze=False,
        constrained_layout=False,
    )

    flat_axes = axes.ravel()
    for idx, spec in enumerate(panel_specs):
        row_idx = idx // n_cols
        col_idx = idx % n_cols
        plot_frame(
            ax=flat_axes[idx],
            state=spec["state"],
            trace=spec["trace"],
            policy_name=spec["policy_name"],
            frame_time=spec["frame_time"],
            xlim=xlim,
            ylim=ylim,
            is_winner=spec["is_winner"],
            show_ylabel=(col_idx == 0),
        )

    for ax in flat_axes[n_panels:]:
        ax.axis("off")

    fig.suptitle(
        (
            f"Actual rollout from selected state: {selected_for} vs {runner_up}\n"
            f"{scenario_name}\n"
            f"{selected_for}: {winner_summary['future_intercepted']} intercepted, "
            f"{winner_summary['future_escaped']} escaped | "
            f"{runner_up}: {runner_summary['future_intercepted']} intercepted, "
            f"{runner_summary['future_escaped']} escaped"
        ),
        fontsize=15,
        fontweight="bold",
        y=0.985,
    )

    # Per-panel legends are placed outside each axis inside plot_frame().
    # Leave enough horizontal space between panels and below each row for the
    # compact diagnostic info boxes.
    fig.subplots_adjust(
        left=0.055,
        right=0.90,
        top=0.86,
        bottom=0.085,
        wspace=0.72,
        hspace=0.70,
    )

    safe_scenario = scenario_name.replace("/", "_").replace("\\", "_")
    path = output_dir / f"actual_trace_{selected_for}_vs_{runner_up}_{safe_scenario}.png"
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    return path

def create_actual_trace_examples(
    selected_df: pd.DataFrame,
    perf_df: pd.DataFrame,
    output_dir: Path,
    generator_seed: int,
    scenario_mix: str,
    n_scenarios: int | None,
    min_threat_speed: float,
    min_boundary_speed: float,
    max_frames: int,
    panels_per_row: int,
    zoom_context_radius: float,
    max_left_penetration: float,
) -> pd.DataFrame:
    rows = []

    for _, row in selected_df.iterrows():
        selected_for = str(row["selected_for"])
        scenario_name = str(row["scenario"])

        print("=" * 90)
        print(f"Selected heuristic: {selected_for}")
        print(f"Scenario: {scenario_name}")

        runner_up = choose_runner_up(perf_df, selected_for)
        print(f"Runner-up: {runner_up}")

        env_snapshot = replay_behavior_to_selected_state(
            row,
            generator_seed=generator_seed,
            scenario_mix=scenario_mix,
            n_scenarios=n_scenarios,
            min_threat_speed=min_threat_speed,
            min_boundary_speed=min_boundary_speed,
        )

        winner_result = trace_from_env_snapshot(env_snapshot, selected_for, preempt=False)
        runner_result = trace_from_env_snapshot(env_snapshot, runner_up, preempt=False)

        path = plot_trace_comparison(
            selected_for=selected_for,
            scenario_name=scenario_name,
            winner_trace=winner_result["trace"],
            runner_trace=runner_result["trace"],
            winner_summary=winner_result["summary"],
            runner_summary=runner_result["summary"],
            runner_up=runner_up,
            output_dir=output_dir,
            max_frames=max_frames,
            panels_per_row=panels_per_row,
            zoom_context_radius=zoom_context_radius,
            max_left_penetration=max_left_penetration,
        )

        print(f"Saved actual trace figure: {path}")

        rows.append(
            {
                "selected_for": selected_for,
                "scenario": scenario_name,
                "runner_up": runner_up,
                "start_t": winner_result["summary"]["start_t"],
                "winner_future_intercepted": winner_result["summary"]["future_intercepted"],
                "winner_future_escaped": winner_result["summary"]["future_escaped"],
                "runner_future_intercepted": runner_result["summary"]["future_intercepted"],
                "runner_future_escaped": runner_result["summary"]["future_escaped"],
                "figure_path": str(path),
            }
        )

    out = pd.DataFrame(rows)
    out.to_csv(output_dir / "actual_trace_figure_summary.csv", index=False)
    return out


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create real simulation trace figures for representative heuristic states. "
            "This reconstructs the selected state, rolls out the winning heuristic and "
            "the runner-up heuristic from that same state, and plots actual frames."
        )
    )

    parser.add_argument(
        "--selected-dir",
        required=True,
        type=str,
        help="Directory created by select_representative_heuristic_states.py.",
    )

    parser.add_argument(
        "--output-dir",
        default=None,
        type=str,
        help="Output directory. Default: selected-dir/actual_trace_figures",
    )

    parser.add_argument(
        "--generator-seed",
        type=int,
        default=42,
        help="Seed used by make_large_scale_scenarios. Default: 42.",
    )

    parser.add_argument(
        "--scenario-mix",
        type=str,
        default="baseline",
        choices=["baseline", "decision_rich", "heavy_load"],
        help=(
            "Scenario mix used when the rollout scenarios were generated. "
            "Use decision_rich for the decision-rich overnight experiments. "
            "Default: baseline."
        ),
    )

    parser.add_argument(
        "--n-scenarios",
        type=int,
        default=None,
        help=(
            "Number of large-scale scenarios in the original rollout. "
            "Optional, but recommended for long runs such as 5000. "
            "If omitted, the script regenerates only up to each selected scenario index."
        ),
    )

    parser.add_argument(
        "--min-threat-speed",
        type=float,
        default=0.05,
        help="Minimum stochastic target speed used in scenario regeneration.",
    )

    parser.add_argument(
        "--min-boundary-speed",
        type=float,
        default=0.05,
        help="Minimum stochastic target boundary-direction speed used in scenario regeneration.",
    )

    parser.add_argument(
        "--max-frames",
        type=int,
        default=4,
        help="Number of time frames per figure. Default: 4.",
    )

    parser.add_argument(
        "--panels-per-row",
        type=int,
        default=2,
        help="Number of subplots per row in each trace figure. Default: 2.",
    )

    parser.add_argument(
        "--zoom-context-radius",
        type=float,
        default=12.0,
        help=(
            "Local context radius for targets included in the plot limits. "
            "Larger values show more surrounding targets; smaller values zoom in. "
            "Default: 12.0."
        ),
    )

    parser.add_argument(
        "--max-left-penetration",
        type=float,
        default=3.0,
        help=(
            "Maximum x<0 span to keep in the automatic zoom window unless needed by the local focus. "
            "Default: 3.0."
        ),
    )

    return parser.parse_args()


