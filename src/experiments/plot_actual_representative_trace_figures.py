def parse_scenario_index(scenario_name: str) -> int:
    # Example: large_00248_overloaded_clustered_poisson_tight
    parts = scenario_name.split("_")
    if len(parts) < 2 or parts[0] != "large":
        raise ValueError(f"Could not parse large-scale scenario id from: {scenario_name}")
    return int(parts[1])


def load_selected_examples(input_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    selected_path = input_dir / "selected_representative_states_full_rows.csv"
    perf_path = input_dir / "selected_representative_state_performance_long.csv"

    if not selected_path.exists():
        raise FileNotFoundError(
            f"Missing selected states file: {selected_path}\n"
            "Run select_representative_heuristic_states.py first."
        )

    if not perf_path.exists():
        raise FileNotFoundError(
            f"Missing performance file: {perf_path}\n"
            "Run select_representative_heuristic_states.py first."
        )

    return pd.read_csv(selected_path), pd.read_csv(perf_path)


def get_scenario_params(scenario_name: str, seed: int):
    scenario_index = parse_scenario_index(scenario_name)
    scenarios = make_large_scale_scenarios(n_scenarios=scenario_index + 1, seed=seed)

    if scenario_name not in scenarios:
        raise KeyError(
            f"Scenario {scenario_name} was not regenerated. "
            f"Check that the large-scale generator seed is {seed}."
        )

    return scenarios[scenario_name].params


def replay_behavior_to_selected_state(row: pd.Series, generator_seed: int) -> SimEnv:
    """
    Reconstruct the exact environment snapshot used by the state-labeling dataset.

    The selected row was generated by:
    1. Running a behavior heuristic.
    2. Labeling every decision state.
    3. Assigning state_id in that behavior trajectory.

    This function repeats that process until the requested state_id.
    """

    scenario_name = str(row["scenario"])
    params = get_scenario_params(scenario_name, seed=generator_seed)

    behavior_heuristic = str(row.get("behavior_heuristic", "NI"))
    behavior_preempt = bool(row.get("behavior_preempt", False))
    target_state_id = int(row.get("state_id", 0))

    env = SimEnv(params)
    heuristic_map = make_heuristics(seed=params.seed)

    if behavior_heuristic not in heuristic_map:
        raise KeyError(f"Unknown behavior heuristic: {behavior_heuristic}")

    behavior_h = heuristic_map[behavior_heuristic]

    target_id = None
    state_counter = 0

    while not env.done():
        active = env.active_threats()
        should_label = len(active) > 0

        if should_label:
            if state_counter == target_state_id:
                return copy.deepcopy(env)
            state_counter += 1

        active = env.active_threats()

        if target_id is None or all(th.id != target_id for th in active):
            target_id = behavior_h(active, env.interceptor_pos, params.v_interceptor)

        events = env.step(target_id)

        if behavior_preempt and events.get("arrival", 0) > 0:
            active_after = env.active_threats()
            target_id = behavior_h(active_after, env.interceptor_pos, params.v_interceptor)

    raise RuntimeError(
        f"Could not replay to state_id={target_state_id} for scenario={scenario_name}. "
        f"Reached only {state_counter} labeled states."
    )


def snapshot_features(env: SimEnv) -> dict[str, Any]:
    active = env.active_threats()

    if not active:
        return {
            "N_active": 0,
            "min_ttb": np.inf,
            "mean_ttb": np.inf,
            "min_tti": np.inf,
            "mean_tti": np.inf,
            "min_slack": np.inf,
            "mean_slack": np.inf,
            "min_positive_slack": np.inf,
            "count_feasible": 0,
            "count_negative_slack": 0,
            "feasible_ratio": 0.0,
        }

    ttbs = np.array([time_to_boundary_x0(th.pos, th.vel) for th in active], dtype=float)
    ttis = np.array([time_to_intercept(env.interceptor_pos, th.pos, env.p.v_interceptor) for th in active], dtype=float)
    slacks = np.array([slack(env.interceptor_pos, th, env.p.v_interceptor) for th in active], dtype=float)
    positive = slacks[slacks >= 0]

    finite_ttbs = ttbs[np.isfinite(ttbs)]
    finite_ttis = ttis[np.isfinite(ttis)]
    finite_slacks = slacks[np.isfinite(slacks)]

    return {
        "N_active": int(len(active)),
        "min_ttb": float(np.min(finite_ttbs)) if len(finite_ttbs) else np.inf,
        "mean_ttb": float(np.mean(finite_ttbs)) if len(finite_ttbs) else np.inf,
        "min_tti": float(np.min(finite_ttis)) if len(finite_ttis) else np.inf,
        "mean_tti": float(np.mean(finite_ttis)) if len(finite_ttis) else np.inf,
        "min_slack": float(np.min(finite_slacks)) if len(finite_slacks) else np.inf,
        "mean_slack": float(np.mean(finite_slacks)) if len(finite_slacks) else np.inf,
        "min_positive_slack": float(np.min(positive)) if len(positive) else np.inf,
        "count_feasible": int(np.sum(slacks >= 0)),
        "count_negative_slack": int(np.sum(slacks < 0)),
        "feasible_ratio": float(np.mean(slacks >= 0)),
    }


def trace_from_env_snapshot(
    env_snapshot: SimEnv,
    heuristic_name: str,
    preempt: bool = False,
) -> dict[str, Any]:
    """
    Continue an actual simulation from the selected environment state
    using a fixed heuristic, while recording a trace.
    """

    env = copy.deepcopy(env_snapshot)
    heuristic_map = make_heuristics(seed=env.p.seed)

    if heuristic_name not in heuristic_map:
        raise KeyError(f"Unknown heuristic: {heuristic_name}")

    h = heuristic_map[heuristic_name]

    start_t = float(env.t)
    start_intercepted = int(env.intercepted)
    start_escaped = int(env.escaped)
    start_spawned = int(env.spawned)

    target_id = None
    trace: list[dict[str, Any]] = []

    while not env.done():
        active_before = env.active_threats()

        if target_id is None or all(th.id != target_id for th in active_before):
            target_id = h(active_before, env.interceptor_pos, env.p.v_interceptor)

        trace.append(
            {
                "t": float(env.t),
                "relative_t": float(env.t - start_t),
                "interceptor_pos": env.interceptor_pos.copy(),
                "chosen_target_id": target_id,
                "active_threats": [
                    {
                        "id": th.id,
                        "pos": th.pos.copy(),
                        "vel": th.vel.copy(),
                        "ttb": float(time_to_boundary_x0(th.pos, th.vel)),
                        "tti": float(time_to_intercept(env.interceptor_pos, th.pos, env.p.v_interceptor)),
                        "slack": float(slack(env.interceptor_pos, th, env.p.v_interceptor)),
                    }
                    for th in active_before
                ],
                "features": snapshot_features(env),
                "intercepted_so_far": int(env.intercepted - start_intercepted),
                "escaped_so_far": int(env.escaped - start_escaped),
                "spawned_so_far": int(env.spawned - start_spawned),
                "total_intercepted": int(env.intercepted),
                "total_escaped": int(env.escaped),
                "total_spawned": int(env.spawned),
            }
        )

        events = env.step(target_id)

        if preempt and events.get("arrival", 0) > 0:
            active_after = env.active_threats()
            target_id = h(active_after, env.interceptor_pos, env.p.v_interceptor)

    summary = {
        "heuristic": heuristic_name,
        "start_t": start_t,
        "future_intercepted": int(env.intercepted - start_intercepted),
        "future_escaped": int(env.escaped - start_escaped),
        "future_spawned": int(env.spawned - start_spawned),
        "final_intercepted": int(env.intercepted),
        "final_escaped": int(env.escaped),
        "final_spawned": int(env.spawned),
    }

    return {"trace": trace, "summary": summary}


def choose_runner_up(perf_df: pd.DataFrame, selected_for: str) -> str:
    g = perf_df[perf_df["selected_for"] == selected_for].copy()

    if g.empty:
        raise ValueError(f"No performance rows for selected_for={selected_for}")

    g = g.sort_values(
        ["future_intercepted", "future_escaped", "rank"],
        ascending=[False, True, True],
    )

    for _, row in g.iterrows():
        h = str(row["heuristic"])
        if h != selected_for:
            return h

    raise ValueError(f"Could not determine runner-up for {selected_for}")


def pick_frame_times(trace_a: list[dict[str, Any]], trace_b: list[dict[str, Any]], max_frames: int) -> list[float]:
    if not trace_a:
        raise ValueError("Winner trace is empty.")
    if not trace_b:
        raise ValueError("Runner-up trace is empty.")

    # Limit to the time range shared by both traces.
    end_t = min(trace_a[-1]["t"], trace_b[-1]["t"])
    start_t = max(trace_a[0]["t"], trace_b[0]["t"])

    if end_t <= start_t:
        return [start_t]

    n = max(2, max_frames)
    return np.linspace(start_t, end_t, n).tolist()


def nearest_state_at_time(trace: list[dict[str, Any]], t: float) -> dict[str, Any]:
    idx = int(np.argmin([abs(state["t"] - t) for state in trace]))
    return trace[idx]


def collect_plot_limits(traces: list[list[dict[str, Any]]]) -> tuple[tuple[float, float], tuple[float, float]]:
    xs = [0.0]
    ys = [0.0]

    for trace in traces:
        for state in trace:
            p = np.array(state["interceptor_pos"])
            xs.append(float(p[0]))
            ys.append(float(p[1]))

            for th in state["active_threats"]:
                pos = np.array(th["pos"])
                xs.append(float(pos[0]))
                ys.append(float(pos[1]))

    if len(xs) == 1:
        return (-1, 10), (-10, 10)

    xmin, xmax = min(xs), max(xs)
    ymin, ymax = min(ys), max(ys)

    xpad = max(1.0, 0.12 * (xmax - xmin + 1e-9))
    ypad = max(1.0, 0.12 * (ymax - ymin + 1e-9))

    # Always include some penetration region on the left of the boundary.
    xlim = (min(-1.0, xmin - xpad), xmax + xpad)
    ylim = (ymin - ypad, ymax + ypad)

    return xlim, ylim


def fmt(x: Any, digits: int = 2) -> str:
    try:
        x = float(x)
        if np.isinf(x):
            return "inf"
        if np.isnan(x):
            return "NA"
        if abs(x - round(x)) < 1e-9:
            return str(int(round(x)))
        return f"{x:.{digits}f}"
    except Exception:
        return str(x)


def plot_frame(
    ax,
    state: dict[str, Any],
    trace: list[dict[str, Any]],
    policy_name: str,
    frame_time: float,
    xlim: tuple[float, float],
    ylim: tuple[float, float],
    is_winner: bool,
    show_ylabel: bool,
) -> None:
    # Penetration region
    ax.axvspan(xlim[0], 0, color="#ffdddd", alpha=0.45, zorder=0)
    ax.axvline(0, color="red", linestyle="--", linewidth=1.4, zorder=1)

    # Interceptor path until this time
    path_points = [
        np.array(s["interceptor_pos"], dtype=float)
        for s in trace
        if s["t"] <= state["t"]
    ]
    if len(path_points) >= 2:
        path = np.vstack(path_points)
        ax.plot(path[:, 0], path[:, 1], color="black", linewidth=1.7, alpha=0.85, zorder=2)

    pI = np.array(state["interceptor_pos"], dtype=float)

    # Threats and velocity arrows
    active = state["active_threats"]
    chosen_id = state["chosen_target_id"]

    for th in active:
        pos = np.array(th["pos"], dtype=float)
        vel = np.array(th["vel"], dtype=float)
        is_chosen = th["id"] == chosen_id

        color = "#1f77b4"
        size = 38
        z = 3

        if is_chosen:
            color = "#2ca02c"
            size = 75
            z = 5

        ax.scatter(pos[0], pos[1], s=size, color=color, edgecolor="black", linewidth=0.4, zorder=z)

        # Velocity direction arrow, scaled for visibility.
        speed = np.linalg.norm(vel)
        if speed > 1e-9:
            unit = vel / speed
            arrow_len = max(0.35, 0.05 * (xlim[1] - xlim[0]))
            ax.arrow(
                pos[0],
                pos[1],
                unit[0] * arrow_len,
                unit[1] * arrow_len,
                head_width=0.18,
                head_length=0.28,
                length_includes_head=True,
                color="#1f77b4" if not is_chosen else "#2ca02c",
                alpha=0.55,
                zorder=2,
            )

    # Interceptor
    ax.scatter(pI[0], pI[1], s=90, color="black", marker="*", zorder=6)

    # Chosen target arrow
    chosen = None
    for th in active:
        if th["id"] == chosen_id:
            chosen = th
            break

    if chosen is not None:
        cpos = np.array(chosen["pos"], dtype=float)
        ax.annotate(
            "",
            xy=(cpos[0], cpos[1]),
            xytext=(pI[0], pI[1]),
            arrowprops=dict(arrowstyle="->", color="#2ca02c", linewidth=1.6),
            zorder=4,
        )
        ax.scatter(
            cpos[0],
            cpos[1],
            s=180,
            facecolors="none",
            edgecolors="#2ca02c",
            linewidth=2.2,
            zorder=6,
        )

    f = state["features"]

    info = (
        f"t = {state['t']:.2f}\n"
        f"N active = {f.get('N_active', len(active))}\n"
        f"min TTB = {fmt(f.get('min_ttb'))}\n"
        f"min slack = {fmt(f.get('min_slack'))}\n"
        f"min +slack = {fmt(f.get('min_positive_slack'))}\n"
        f"future I/E so far = {state['intercepted_so_far']} / {state['escaped_so_far']}"
    )

    ax.text(
        0.02,
        0.98,
        info,
        transform=ax.transAxes,
        va="top",
        ha="left",
        fontsize=8.5,
        bbox=dict(boxstyle="round,pad=0.30", facecolor="white", edgecolor="gray", alpha=0.92),
    )

    title_prefix = "WINNER" if is_winner else "RUNNER-UP"
    ax.set_title(f"{title_prefix}: {policy_name} | frame t={state['t']:.2f}", fontsize=11)

    ax.set_xlim(*xlim)
    ax.set_ylim(*ylim)
    ax.set_xlabel("x position")
    if show_ylabel:
        ax.set_ylabel("y position")
    ax.grid(alpha=0.25)


def plot_trace_comparison(
    selected_for: str,
    scenario_name: str,
    winner_trace: list[dict[str, Any]],
    runner_trace: list[dict[str, Any]],
    winner_summary: dict[str, Any],
    runner_summary: dict[str, Any],
    runner_up: str,
    output_dir: Path,
    max_frames: int,
) -> Path:
    frame_times = pick_frame_times(winner_trace, runner_trace, max_frames=max_frames)
    xlim, ylim = collect_plot_limits([winner_trace, runner_trace])

    n_rows = len(frame_times)
    fig, axes = plt.subplots(
        n_rows,
        2,
        figsize=(14.5, 4.0 * n_rows),
        squeeze=False,
        constrained_layout=True,
    )

    for r, t in enumerate(frame_times):
        w_state = nearest_state_at_time(winner_trace, t)
        b_state = nearest_state_at_time(runner_trace, t)

        plot_frame(
            ax=axes[r, 0],
            state=w_state,
            trace=winner_trace,
            policy_name=selected_for,
            frame_time=t,
            xlim=xlim,
            ylim=ylim,
            is_winner=True,
            show_ylabel=True,
        )

        plot_frame(
            ax=axes[r, 1],
            state=b_state,
            trace=runner_trace,
            policy_name=runner_up,
            frame_time=t,
            xlim=xlim,
            ylim=ylim,
            is_winner=False,
            show_ylabel=False,
        )

    fig.suptitle(
        (
            f"Actual rollout from selected state: {selected_for} vs {runner_up}\n"
            f"{scenario_name}\n"
            f"{selected_for}: {winner_summary['future_intercepted']} intercepted, "
            f"{winner_summary['future_escaped']} escaped | "
            f"{runner_up}: {runner_summary['future_intercepted']} intercepted, "
            f"{runner_summary['future_escaped']} escaped"
        ),
        fontsize=15,
        fontweight="bold",
    )

    safe_scenario = scenario_name.replace("/", "_").replace("\\", "_")
    path = output_dir / f"actual_trace_{selected_for}_vs_{runner_up}_{safe_scenario}.png"
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    return path


def create_actual_trace_examples(
    selected_df: pd.DataFrame,
    perf_df: pd.DataFrame,
    output_dir: Path,
    generator_seed: int,
    max_frames: int,
) -> pd.DataFrame:
    rows = []

    for _, row in selected_df.iterrows():
        selected_for = str(row["selected_for"])
        scenario_name = str(row["scenario"])

        print("=" * 90)
        print(f"Selected heuristic: {selected_for}")
        print(f"Scenario: {scenario_name}")

        runner_up = choose_runner_up(perf_df, selected_for)
        print(f"Runner-up: {runner_up}")

        env_snapshot = replay_behavior_to_selected_state(row, generator_seed=generator_seed)

        winner_result = trace_from_env_snapshot(env_snapshot, selected_for, preempt=False)
        runner_result = trace_from_env_snapshot(env_snapshot, runner_up, preempt=False)

        path = plot_trace_comparison(
            selected_for=selected_for,
            scenario_name=scenario_name,
            winner_trace=winner_result["trace"],
            runner_trace=runner_result["trace"],
            winner_summary=winner_result["summary"],
            runner_summary=runner_result["summary"],
            runner_up=runner_up,
            output_dir=output_dir,
            max_frames=max_frames,
        )

        print(f"Saved actual trace figure: {path}")

        rows.append(
            {
                "selected_for": selected_for,
                "scenario": scenario_name,
                "runner_up": runner_up,
                "start_t": winner_result["summary"]["start_t"],
                "winner_future_intercepted": winner_result["summary"]["future_intercepted"],
                "winner_future_escaped": winner_result["summary"]["future_escaped"],
                "runner_future_intercepted": runner_result["summary"]["future_intercepted"],
                "runner_future_escaped": runner_result["summary"]["future_escaped"],
                "figure_path": str(path),
            }
        )

    out = pd.DataFrame(rows)
    out.to_csv(output_dir / "actual_trace_figure_summary.csv", index=False)
    return out


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create real simulation trace figures for representative heuristic states. "
            "This reconstructs the selected state, rolls out the winning heuristic and "
            "the runner-up heuristic from that same state, and plots actual frames."
        )
    )

    parser.add_argument(
        "--selected-dir",
        required=True,
        type=str,
        help="Directory created by select_representative_heuristic_states.py.",
    )

    parser.add_argument(
        "--output-dir",
        default=None,
        type=str,
        help="Output directory. Default: selected-dir/actual_trace_figures",
    )

    parser.add_argument(
        "--generator-seed",
        type=int,
        default=42,
        help="Seed used by make_large_scale_scenarios. Default: 42.",
    )

    parser.add_argument(
        "--max-frames",
        type=int,
        default=4,
        help="Number of time frames per figure. Default: 4.",
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    selected_dir = Path(args.selected_dir)
    output_dir = Path(args.output_dir) if args.output_dir else selected_dir / "actual_trace_figures"
    output_dir.mkdir(parents=True, exist_ok=True)

    print("=== Actual Representative Trace Figures ===")
    print(f"Selected directory: {selected_dir}")
    print(f"Output directory:   {output_dir}")
    print(f"Generator seed:     {args.generator_seed}")
    print(f"Max frames:         {args.max_frames}")

    selected_df, perf_df = load_selected_examples(selected_dir)

    summary = create_actual_trace_examples(
        selected_df=selected_df,
        perf_df=perf_df,
        output_dir=output_dir,
        generator_seed=args.generator_seed,
        max_frames=args.max_frames,
    )

    print("\nActual trace figure summary")
    print("---------------------------")
    print(summary.to_string(index=False))

    print("\nDone.")
    print(f"Saved outputs to: {output_dir}")


if __name__ == "__main__":
    main()
